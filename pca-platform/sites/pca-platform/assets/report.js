  var NARR = null;
  function nar(id) {
    if (!NARR) return '';
    var v = NARR[id];
    if (!v || !v.length) return '';
    return v.map(function (t) { return '<p>' + esc(t) + '</p>'; }).join('');
  }

  /* ── 방사형 ────────────────────────────────────────── */
  function radar(points, opts) {
    opts = opts || {};
    var n = points.length, W = 640, H = 470, cx = 320, cy = 232, R = 132, LAB = R + 34;
    function at(i, v) {
      var a = -Math.PI / 2 + (2 * Math.PI * i) / n, r = R * v / 100;
      return [cx + r * Math.cos(a), cy + r * Math.sin(a)];
    }
    function poly(v, cls) {
      return '<polygon class="' + cls + '" points="' + points.map(function (_, i) {
        var q = at(i, v); return q[0].toFixed(1) + ',' + q[1].toFixed(1);
      }).join(' ') + '"/>';
    }
    var g = '';
    [20, 40, 60, 80, 100].forEach(function (v) { g += poly(v, 'rp-ring' + (v === 100 ? ' rp-ring-out' : '')); });
    points.forEach(function (_, i) {
      var q = at(i, 100);
      g += '<line class="rp-spoke" x1="' + cx + '" y1="' + cy + '" x2="' + q[0].toFixed(1) + '" y2="' + q[1].toFixed(1) + '"/>';
    });
    [20, 40, 60, 80, 100].forEach(function (v) {
      var q = at(0, v);
      g += '<text class="rp-tick" x="' + (cx + 7) + '" y="' + (q[1] + 3.5).toFixed(1) + '">' + v + '</text>';
    });
    /* 비교 계열. 뒤에 점선으로 깔고 본 계열을 그 위에 얹는다 */
    var base = '';
    if (opts.cmp && opts.cmp.length === n) {
      base = '<polygon class="rp-cmp" points="' + opts.cmp.map(function (v, i) {
        var q = at(i, v); return q[0].toFixed(1) + ',' + q[1].toFixed(1);
      }).join(' ') + '"/>';
    }
    var shape = '<polygon class="rp-poly" points="' + points.map(function (pt, i) {
      var q = at(i, pt.v); return q[0].toFixed(1) + ',' + q[1].toFixed(1);
    }).join(' ') + '"/>';
    var dots = points.map(function (pt, i) {
      var q = at(i, pt.v);
      return '<circle class="rp-dot" cx="' + q[0].toFixed(1) + '" cy="' + q[1].toFixed(1) + '" r="3.4"/>';
    }).join('');
    var labs = points.map(function (pt, i) {
      var a = -Math.PI / 2 + (2 * Math.PI * i) / n, cs = Math.cos(a), sn = Math.sin(a);
      var x = cx + LAB * cs, y = cy + LAB * sn, anchor, base;
      if (Math.abs(cs) < 0.28) { anchor = 'middle'; y += sn < 0 ? -10 : 18; base = 'auto'; }
      else { anchor = cs > 0 ? 'start' : 'end'; base = 'middle'; }
      return '<g class="rp-lab"><text x="' + x.toFixed(1) + '" y="' + y.toFixed(1) +
        '" text-anchor="' + anchor + '" dominant-baseline="' + base + '">' + esc(pt.n) +
        '<tspan x="' + x.toFixed(1) + '" dy="15">' + pt.v +
        (opts.cmp && opts.cmp.length === n ? ' / ' + opts.cmp[i] : '') + '</tspan></text></g>';
    }).join('');
    return '<div class="rp-chart"><div class="rp-chart-t">' + esc(opts.title || '') + '</div>' +
      '<svg class="rp-radar" viewBox="0 0 ' + W + ' ' + H + '" role="img" aria-label="' +
      esc(opts.title || '') + '">' + g + base + shape + dots + labs + '</svg>' +
      (opts.legend ? '<div class="rp-legend">' + opts.legend + '</div>' : '') +
      (opts.foot ? '<p class="rp-chart-f">' + opts.foot + '</p>' : '') + '</div>';
  }


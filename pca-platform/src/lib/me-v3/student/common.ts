/**
 * **영역에 걸치지 않는 판단(공통 판단 · 학위 묶음)의 이름을 Core 마다 든다**
 * (R34 · Staging PDF 9쪽에서 찾은 자리).
 *
 * 전에는 `result/text.ko.ts` 의 `COMMON_ITEM_KO` 한 벌이 스무 Core 전부에
 * 나갔다. 그 벌이 기계공학의 말이라(`조건이나 치수를 직접 정하기` ·
 * `실험값과 계산값을 대조해` · `실험이나 해석의 조건`) 경영학과 학생의
 * 종이 9쪽에 그 말이 그대로 섰다. 번역 보기(`student/translate.ts`)와
 * 같은 종류이고, 한 Core 의 값을 공통 층에 박아 둔 버릇의 다음 번이다.
 *
 * **측정은 바뀌지 않는다.** 문항 번호와 축과 확인·소유 판정은 결과 모델이
 * 이미 들고 있고(`CommonView.items`), 여기서는 그 번호를 **그 Core 의 문항이
 * 실제로 물은 말**로 부르기만 한다. 줄인 말은 그 Core 의 문항 은행 문면에서
 * 왔다: 문면을 그대로 쓰지 않는 까닭은 목록에서 `~한 적 있나요?` 가 열두 번
 * 되풀이되면 읽히지 않기 때문이다.
 *
 * 기계공학 벌은 전의 글자 그대로이고(`text.ko.ts` 의 표를 그대로 옮겼다),
 * 열아홉 Core 가 같은 문면을 쓰는 자리는 `NEUTRAL` 하나로 들며, 문면이 그
 * Core 의 말로 갈리는 자리(`CJ_GIVEN_REV` · `CJ_REQUIRE` · `MS_*` · `PD_OUT` ·
 * `PD_LINK`)만 Core 마다 따로 적는다. **적지 않은 번호는 세우지 않는다**:
 * 문항 번호를 화면에 내보내는 것보다 그 줄을 비우는 쪽이 낫고, 비면
 * `v3:student` 가 먼저 걸린다.
 */
export type CommonLabels = Record<string, string>;


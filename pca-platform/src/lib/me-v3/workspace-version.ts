/**
 * 작업공간의 판본. **검사와 결과지와 또 따로 올린다.**
 *
 * 넷이 따로 간다: 검사 화면 · 결과지 화면 · 판단 규칙 · 작업공간.
 * 한 판본으로 묶으면 홈의 카드 하나를 옮긴 날 **이미 응시한 사람의
 * 결과를 다시 계산해야 하는지** 묻게 된다. 작업공간은 기존 검사 엔진
 * 위에 올라가는 사용자 경험 층이고, 그 아래의 판정에 닿지 않는다.
 */

/**
 * 작업공간 화면. 쪽이 늘거나 띠의 묶음이 바뀌면 올린다.
 *
 * `V1` 인 까닭. **개인 쪽이 둘이었고 로그인이 틀린 쪽으로 떨어졌다.**
 * `/my` 는 옛 표(`attempts` · `report_snapshots` · `evidence_profiles`)를
 * 읽고 `/me` 는 V3 표를 읽는데, `homePathFor('student')` 가 앞쪽을
 * 가리켰다. 그래서 기계공학 V3 를 끝낸 사람이 로그인하면 `아직 응시한
 * 검사가 없습니다` 를 읽고, 그 화면의 주된 단추가 옛 검사로 보냈다.
 *
 * 이번 판본이 세운 것은 셋이다.
 *
 *   하나. **하나의 앱 안이라는 느낌.** 넓은 화면은 왼쪽에 늘 보이는 띠고
 *   손전화는 아래 띠와 서랍이다. 띠의 줄을 넷으로 묶었다(지금 · 내 기록 ·
 *   넓게 보기 · 준비 중). 쪽을 옮겨도 `지금 어디인지` 가 끊기지 않는다.
 *
 *   둘. **굳은 기록과 지금 값을 생김새로 가른다.** 검사 당시 결과는 흰
 *   카드에 날짜 띠와 자물쇠 표시, 지금 상태는 꺼진 바탕에 점선이다.
 *   같은 카드로 그리면 날짜만 다른 같은 값으로 읽힌다.
 *
 *   셋. **상태마다 다른 화면.** 검사 전인 사람과 경험까지 반영한 사람이
 *   같은 카드 아홉 칸을 받고 있었다. 빈 카드를 줄줄이 세우면 읽는 사람은
 *   자기 결과가 덜 만들어진 줄 안다.
 *
 * `/my` 는 계정 영역으로 남는다. 로그인과 주문과 파기, 그리고 옛 검사
 * 기록처럼 한 번씩 들르는 줄이다.
 *
 * ## V3 에서 고친 것 (2026-10-09)
 *
 *   **한 route 가 남의 메뉴를 켜고 있었다.** `/me/apply` 가 쪽에서
 *   `/me/jobs` 를 넘기고 그 별칭이 `/me/track` 으로 다시 접혀서,
 *   `지원한 곳` 을 열면 `Track` 이 켜졌다. `/me/region` 도 같은 모양으로
 *   `산업과 직무` 를 켰다. 둘 다 제 줄을 넘기게 고쳤고, 다시 생기지
 *   않게 `ALIAS_OK` 와 `navKnown()` 을 두고 `v3:workspace` 가 센다.
 *
 *   **`준비 중` 묶음 안에 되는 기능 셋이 섞여 있었다.** 관심 산업·직무
 *   바꾸기와 지원한 곳 관리가 Track 안에서 `지금 열기` 로만 닿았다.
 *   준비 중 묶음 안에서만 닿는 기능은 사용자에게 없는 기능이고, 같은
 *   목록에 되는 것과 안 되는 것이 같은 모양으로 서면 묶음 이름이
 *   거짓말을 한다. 셋을 제자리로 보내고 Track 에는 아직 없는 것만 뒀다.
 *
 *   **홈이 세부 쪽을 대신하고 있었다.** 묶음마다 셋씩(최대 여섯 줄)과
 *   비어 있는 자리 셋을 홈이 들어서, `지금 상태` 와 `다음 할 일` 을
 *   눌러 들어갈 이유가 없었다. 홈은 상태 셋 · 비어 있는 자리 하나 ·
 *   할 일 하나이고 나머지는 세부 쪽이다.
 *
 *   **결과 기록이 서랍 안에 있었다.** 검사를 끝낸 사람이 가장 자주
 *   돌아오는 자리인데 손전화 띠에 없었다. 띠를 여섯 칸으로 늘리지 않고
 *   (320px 에서 글자가 두 줄로 접힌다) `지금 상태` 와 자리를 바꿨다 —
 *   그쪽은 홈의 첫 카드가 요약을 들고 있다.
 *
 *   **`/my` 에 `로그인 방법` 이 섰다.** 소셜 로그인이 붙어서, 이 계정에
 *   들어오는 길이 지금 무엇인지 적지 않으면 구글로 가입하신 분이
 *   비밀번호 찾기를 누르고 메일을 기다린다.
 */

/**
 * V8 · copy.7 (2026-10-10). 경험에서 현재 상태를 거쳐 다음 행동까지.
 *
 * **판정 코드는 한 줄도 바뀌지 않았다.** `currentState()` 와
 * `previewRecompute()` 와 `applyRecompute()` 가 그대로고, 굳은 스냅샷도
 * 그대로다. 측정은 `ME_V3_MEASUREMENT_FREEZE_1` 에 머문다. 바뀐 것은
 * 같은 값을 어떤 차례로 어떤 말로 내보내는가다.
 *
 * **저장과 반영의 구조를 바꾸지 않았다**(규격 §6). 저장하면 무엇이
 * 달라지는지 먼저 보여 주고, 사람이 누를 때 반영한다. 자동 반영으로
 * 바꾸면 계산이 깨진 날 저장까지 막히고, 무엇이 달라지는지 모른 채
 * 숫자만 바뀐다.
 *
 * 1. **경험을 세 걸음으로 적는다**(규격 §3·§4): 무슨 경험이었나 · 어떤
 *    기술 판단이었나 · 무엇이 남았나. **DB 구조를 한 줄도 바꾸지 않았고
 *    저장도 끝에서 한 번이다**: 걸음마다 저장하면 둘째에서 닫은 기록이
 *    반쪽으로 남고 그 반쪽이 판정에 들어간다.
 * 2. **저장 직후 화면이 다섯을 차례로 적는다**(규격 §5): 저장됐다 ·
 *    이번 경험에서 새로 연결된 것 · 현재 상태에서 달라지는 것 · 그다음에
 *    할 일 · 어디로. 전에는 머리에 숫자 카드 셋과 여섯 칸짜리 표가 먼저
 *    섰고, **적은 사람이 묻는 것에 그 수가 답하지 않았다.** 이번 경험으로
 *    좁히려고 저장할 때 그 기록의 번호를 들고 간다(`?new=`).
 * 3. **달라진 것이 없으면 그 사실과 까닭을 적는다**(규격 §13). 까닭
 *    셋을 가린다: 기술영역을 고르지 않았는가 · 이미 확인된 범위인가 ·
 *    같은 자리의 근거가 아직 하나인가.
 * 4. **같은 변화를 세 화면이 한 말로 적는다**(규격 §12). 홈의 `최근
 *    변화` 와 저장 직후와 현재 상태가 `change-text.ko.ts` 하나를
 *    부른다. 따로 적으면 같은 변화가 서로 다른 말로 읽히고 어느 날 한
 *    곳만 고쳐진다. **`경험이 추가되었습니다` 로 적지 않는다.**
 * 5. **현재 상태 첫 화면의 차례를 §7 이 정한다**: 현재 상태 → 최근
 *    반영 → 지금 설명할 수 있는 영역 → 최근 달라진 것 → 아직 부족한 것 →
 *    다음 행동. 세부(전체 기술영역 · 자리별 근거 · 산업과 직무 · 지역)는
 *    그 아래다.
 * 6. **굳은 결과와 지금 값을 점수처럼 견주지 않는다**(규격 §8). 두 칸을
 *    나란히 두고 각 칸이 무엇인지와 **서로를 덮지 않는다**는 것을 적는다.
 *    `+1점` 도 `2 → 3` 도 쓰지 않는다.
 * 7. **다음 할 일이 할 수 있는 일 하나가 됐다**(규격 §9·§10). 줄마다
 *    넷이 붙는다: 무엇을 할지 · 왜 필요한지 · 어느 빈자리와 이어지는지 ·
 *    어떤 경험으로 메우는지. 첫 화면에 하나만 강조하고 나머지는 접는다.
 *    그 칸에 `경험에 추가` 가 붙어 루프가 그 자리에서 이어진다.
 * 8. **경험 목록이 다섯만 적는다**(규격 §14): 제목 · 유형 · 날짜 ·
 *    연결된 기술영역 · 반영 여부. 전에는 아홉 칸이었고 그중 다섯이
 *    `문제 3개` 같은 개수였다. 고른 항목은 눌러서 펼친다.
 * 9. **저장 실패와 반영 실패를 가른다**(규격 §19). 앞엣사람은 다시
 *    적어야 하고 뒤엣사람은 다시 적을 일이 없다. 한 문장으로 적으면
 *    뒤엣사람이 처음부터 다시 적어 같은 기록이 두 벌 쌓인다.
 */

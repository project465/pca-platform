/**
 * 결과 모델의 판본. **채점 판본과 따로 올린다.**
 *
 * 결과지의 구조가 바뀌는 것과 판단 규칙이 바뀌는 것은 다른 일이다.
 * 둘을 한 판본으로 묶으면 절 하나를 옮긴 날 이미 응시한 사람의 점수를
 * 다시 계산해야 하는지 묻게 된다.
 */

/** 결과 모델의 구조. 절이 늘거나 칸이 바뀌면 올린다 */
export const RESULT_MODEL_VERSION = "me-v3-result-model.4";

/** 결과지에 나가는 한국어. 문장만 바뀌면 이것만 올린다 */
export const RESULT_COPY_VERSION = "me-v3-result-copy.5";

/**
 * 결과지 화면. **모델·문장과 또 따로 올린다.**
 *
 * 문장 하나를 고친 날 화면 판본까지 올리면, 되짚을 때 무엇이 바뀐
 * 것인지 알 수 없다. 넷이 따로 간다: 화면 · 문장 · 모델 · 판단.
 */
export const RESULT_UI_VERSION = "ME_V3_RESULT_UI_V4";

/*
 * `V3` 으로 올린 까닭. **아홉 절이 한 이야기로 이어졌고 첫 화면이 셋으로
 * 줄었다.**
 *
 * 첫 화면이 넷에서 셋이 됐다: 지금 확인된 것 · 보고 있는 산업과 직무에서
 * 비어 있는 것 · 지금 할 한 가지. 둘째 칸이 `그렇게 본 까닭` 이었는데, 그
 * 까닭은 아래 영역 절이 한 자리에서 말하므로 **첫 화면의 자리는 비어 있는
 * 것에 내줬다.**
 *
 * 산업 절과 직무 절이 같은 함수를 쓴다(`PackBody`). 전에는 두 벌이 거의
 * 같은 markup 을 따로 들고 있었고, 한쪽에 줄을 더하면 다른 쪽이 조용히
 * 뒤처졌다. 그러면서 네 줄이 새로 섰다: **기술영역과 그 자리 양쪽에서
 * 확인된 경험**(지원서에서 가장 먼저 쓸 자리) · 그 팩 문항에서 확인된 판단 ·
 * 그 팩 문항에서 `없다` 로 답하신 판단 · 관련된 기술영역. 그리고 절마다
 * **다음 한 걸음**으로 닫는다.
 *
 * 지역 절에 `이 넷이 모이면 그 조합을 물어볼 수 있습니다`(산업 × 직무 ×
 * 권역 × 기관 유형)가 섰다. 자료가 0줄이어도 열쇠는 보여 준다: 무엇이
 * 모이면 답이 나오는지 알아야 비어 있는 것이 아직으로 읽힌다.
 *
 * 그리고 **종이로 가는 길**이 결과 안에 생겼다(`결과 PDF 저장`). 웹과
 * 종이가 같은 결과 모델을 읽으므로 둘의 판단이 갈리지 않는다.
 */

/*
 * `V2.1` 로 올린 까닭. **받아 두고 읽지 않던 응답이 결과지에 섰다.**
 *
 * 공통 판단 여섯과 학위 묶음 여섯과 산업 문항 여든과 역할 문항 쉰여섯과
 * 타계열 맥락 넷과 강제 선택 둘과 관심 기관 유형과 목표 셋이, 응답을 받아
 * 두고 **어느 코드도 읽지 않는** 상태였다. blueprint 에는 그 자리가 결과
 * 절로 간다고 적혀 있었고 `v3:migrate` 는 그 적힌 값을 세고 있었다. 적어
 * 둔 것과 읽는 것은 다른 일이다.
 *
 * 선 자리는 넷이다. 열두 영역 절 끝에 `영역을 가리지 않고 확인된 판단` 과
 * 고르신 쪽, 산업·직무 절에 `이 산업 문항에서 확인된 판단`, 번역 절 머리에
 * `대학원 경험을 어디에 걸칠지`, 지역 절에 `고르신 자리`다.
 *
 * **Core 판정은 한 줄도 바뀌지 않았다.** 팩 문항은 영역 축 수준을 만들지
 * 않고(`v3:result` 가 산업을 바꿔 가며 센다), 타계열 맥락과 강제 선택은
 * 묶음 안에 차례를 만들지 않는다.
 *
 * `RESULT_MODEL_VERSION` 도 함께 올렸다: 모델에 칸이 넷 늘었다.
 */

/*
 * `V2` 로 올린 까닭. **네 카드가 한 이야기로 이어졌다.**
 *
 * 전에는 기술영역 묶음과 산업과 직무와 Evidence 와 Gap 이 서로 다른
 * 카드였다. 네 번 읽고도 **그래서 이 산업을 보려면 무엇이 더 필요한가**
 * 가 한 문장으로 서지 않았다. 산업 절과 직무 절 머리에 세 토막을 한
 * 문단으로 잇는 줄을 세웠다(`bridgeKo`): 어디에서 무엇이 확인됐다 · 그
 * 산업을 보려면 무엇이 모자라다 · 다음에 무엇을 하면 메워진다. **세 토막
 * 다 모델이 들고 있는 값에서만 온다**: 지어낸 연결 문장은 그 자리에서
 * 가장 그럴듯하게 읽히고 가장 먼저 거짓이 된다.
 *
 * 절이 일곱에서 아홉이 됐다. `어디에서 찾을지`(지역과 기관)와 `이 결과를
 * 어떻게 읽을 것인가`가 들어왔다. 뒤엣것은 전에 접힌 자리에만 있었다:
 * 무엇을 재고 무엇을 재지 않았는지는 결과의 일부라 접어 두면 필요한
 * 사람이 못 찾는다.
 *
 * 그리고 끝에 갈 자리가 생겼다. 전에는 `내 검사 목록으로` 한 줄이었고,
 * **PDF 를 받은 날 이 서비스가 끝났다.** 지금은 내 CareerMatri 와 경험
 * 추가와 Gap 관리와 탐색과 Track 다섯이다.
 *
 * `RESULT_MODEL_VERSION` 도 함께 올렸다: 절이 늘었고 모델이 들고 있는
 * 값을 읽는 자리가 바뀌었다. **판단 규칙은 한 줄도 바뀌지 않았다.**
 */

/*
 * `V1.1` 로 올린 까닭. 할 일이 하나도 없는 응시에서 `다음에 할 일` 절이
 * **머리글과 약속하는 문장만 세우고 그 아래가 비어 있었다.** 열두 영역에
 * 비슷하게 답하면 비어 있는 자리가 안 잡혀 할 일이 0 이 되는데, 읽는
 * 사람에게 그 자리는 고장으로 보인다.
 *
 * 고친 것은 그 절의 문장 하나다. 판정도 모델도 그대로라
 * `RESULT_MODEL_VERSION` 과 채점 판본은 올리지 않는다.
 */

/*
 * 결과지 판본은 올리지 않는다. **문항 은행과 채점 판본만 바뀌었다.**
 *
 * `result-lock.json` 에 그 둘이 함께 적혀 있어서 동결 대조가 걸린다. 결과
 * 모델의 칸과 절과 화면 구조와 문장은 한 줄도 바뀌지 않았으므로
 * `RESULT_MODEL_VERSION` 과 `RESULT_COPY_VERSION` 과 `RESULT_UI_VERSION` 은
 * 그대로 두고 지문만 다시 적는다. 두 판본을 함께 적어 두는 까닭은 **어떤
 * 은행과 어떤 채점으로 만든 결과지인지**가 그 자리에서 보여야 하기 때문이다.
 */

/*
 * 결과지 판본은 더 올리지 않는다. **인쇄 규칙과 한 줄짜리 고침이다.**
 *
 * 종이 첫 쪽이 머리글 두 줄만 남긴 채 비어 뽑혔다. 영역 패널에 걸린
 * `break-inside: avoid` 가 한 쪽에 안 들어가는 상자를 통째로 다음 쪽으로
 * 밀고 있었다. 그리고 공개 전 띠가 종이에 그대로 찍혔다. 둘 다 인쇄
 * 규칙이라 모델도 문장도 바뀌지 않는다.
 *
 * 그리고 `결과 PDF 저장` 을 `Link` 에서 평범한 `a` 로 바꿨다. Next 가
 * 화면에 들어온 `Link` 를 미리 불러오는데, **그 길은 머리 없는 브라우저를
 * 띄워 종이를 만드는 자리다.** 아래까지 내려 읽기만 해도 종이가 한 벌씩
 * 만들어지고 있었다. 지문만 다시 적는다.
 */

/**
 * **재는 말과 학생이 읽는 말을 가른다.**
 *
 *   measurement copy  ≠  student-facing result copy
 *
 * 문항 은행의 체크리스트 문장은 **재기 위해 적은 말**이다. 고르는 사람이
 * 자기 일과 맞는지 가릴 수 있게 짧고 건조하고 한 가지만 가리킨다. 결과지가
 * 그 문장을 그대로 읽어 주면 학생이 받는 것은 자기 이야기가 아니라 **자기가
 * 고른 보기의 복사본**이고, 그 꼴이 결과지를 검사지처럼 읽히게 한다.
 *
 * 그래서 읽는 층에 이 파일 하나를 둔다. 여기서 하는 일은 셋뿐이다.
 *
 * - **뜻을 더하지 않는다.** 낱말을 새로 만들거나 없는 사실을 붙이지 않고,
 *   고르신 문장이 든 내용만 남긴다.
 * - **꼴만 고친다.** 어순과 어미와 몇 안 되는 낱말이 전부다.
 * - **Core 를 모른다.** 한 전공의 한 문장을 글자로 적어 두고 고치지 않는다.
 *   같은 꼴은 스무 Core 어디서나 같은 규칙으로 풀린다.
 *
 * 문항 은행과 채점과 결과 모델은 이 파일을 읽지 않는다. 여기서 바뀌는 것은
 * **화면에 서는 글자**뿐이고, 저장된 응답의 뜻도 판정도 그대로다.
 */

/**
 * 부사구를 앞으로 보낸다.
 *
 * `A를 B를 들어 했다` 는 한 문장에 `를` 이 둘이라 읽다가 한 번 멈춘다.
 * 사람은 그 자리에서 부사구를 앞에 두고 말한다.
 *
 *   여러 안 가운데 하나를 근거를 들어 골랐다
 *   → 근거를 들어 여러 안 가운데 하나를 골랐다
 *
 * **`예를 들어` 는 건드리지 않는다.** 그것은 부사구가 아니라 말버릇이고,
 * 옮기면 문장이 망가진다.
 */
const HOIST = /^(.*[을를])\s(\S+[을를])\s(들어|삼아)\s(.+)$/;

/**
 * 재는 말에만 서는 낱말을 학생의 말로.
 *
 * **최소한으로 둔다.** 늘릴수록 고르신 뜻에서 멀어지고, 그러면 이 파일이
 * 하지 않기로 한 일(뜻을 더하는 일)을 하게 된다. 지금 든 것은 하나다:
 * 기획에서 쓰는 `안`(案)은 글자가 짧아 `안(內·not)` 과 겹쳐 읽히고, 세는
 * 말과 붙어 설 때 특히 그렇다.
 */
const WORD: [RegExp, string][] = [
  [/(^|\s)(여러|두|세|네|몇)\s안(?=\s)/g, "$1$2 방법"],
  [/(^|\s)안\s(둘|셋)(?=[을를\s])/g, "$1방법 $2"],
  /* 세는 말 뒤의 `가운데` 는 사람이 말할 때 `중` 으로 줄인다. 가운데가
     자리를 뜻하는 자리(`한가운데`)는 빈칸이 없어 걸리지 않는다 */
  [/\s가운데\s(?=(하나|둘|셋|넷)[을를])/g, " 중 "],
];

/** 재는 말을 학생의 말로. **어미는 아직 건드리지 않는다** */
export function plainKo(src: string): string {
  let t = src.trim().replace(/[.]$/, "");
  const m = HOIST.exec(t);
  if (m && m[2] !== "예를") t = `${m[2]} ${m[3]} ${m[1]} ${m[4]}`;
  for (const [re, to] of WORD) t = t.replace(re, to);
  return t;
}

/**
 * 말끝.
 *
 * **한 묶음을 전부 `~해요` 로 닫지 않는다.** 같은 어미가 줄마다 되풀이되면
 * 사람이 쓴 글로 읽히지 않는다. 고르신 일은 `~했어요`(그 사람이 한 일),
 * 우리가 덧붙이는 말은 `~있습니다`·`~하면 좋아요` 로 갈라 리듬을 만든다.
 */
export type Ending = "yo" | "nida";

/** `~다` 로 끝나는 재는 말을 학생이 읽는 한 문장으로 */
export function sayKo(src: string, end: Ending = "yo"): string {
  const t = plainKo(src);
  if (!t) return "";
  if (!/[가-힣]다$/.test(t)) {
    /* 이름씨로 끝나는 자리(산출물 이름)는 문장으로 세우지 않는다 */
    return t;
  }
  if (end === "nida") {
    const ch = t.charCodeAt(t.length - 2);
    const jong = (ch - 0xac00) % 28;
    return `${t.slice(0, -1)}${jong !== 0 ? "습니다" : "ㅂ니다"}`;
  }
  return `${t.slice(0, -1)}어요`;
}

/**
 * 손에 남은 것의 이름.
 *
 * 영역 사전의 이름은 세는 말이 붙어 있거나(`사업계획 한 벌`) 이름씨가
 * 그대로 이어 붙어 있다(`목표와 지표 표`). 재는 자리에서는 그 편이 또렷한데
 * 학생 화면에서는 **사람이 쓰지 않는 말**로 읽힌다.
 *
 * **이름을 바꾸지 않는다**: 세는 말을 떼고, 이어 붙은 이름씨 사이에 조사
 * 하나를 넣어 읽히게 하는 것이 전부다.
 */
export function thingKo(label: string): string {
  let t = label.trim();
  t = t.replace(/\s한\s(벌|장|부|건|묶음|권|쪽)$/, "");
  /* **이름씨를 여럿 이어 붙인 자리에만 손댄다.** `목표와 지표 표` 처럼
     앞이 둘 이상이면 사이에 조사가 없어서 읽다가 걸린다. `설계 문서` 나
     `회의 기록` 처럼 두 낱말로 굳은 이름은 그대로 둔다: 거기에 손대면
     그 영역 사전이 적어 둔 이름을 우리가 바꾸는 일이 된다 */
  const m = /^(.+[가-힣])\s(표|문서|기록|목록|대장)$/.exec(t);
  if (m && /[와과·,]/.test(m[1])) return `${m[1]}${josa(m[1])} 정리한 ${m[2]}`;
  return t;
}

function josa(word: string): string {
  const ch = word.charCodeAt(word.length - 1);
  if (ch < 0xac00 || ch > 0xd7a3) return "를";
  return (ch - 0xac00) % 28 === 0 ? "를" : "을";
}

/**
 * 아직 덜 적힌 자리를 **다음 걸음**으로.
 *
 * `아직 적지 않으셨어요` 는 학생을 재는 말이다. 같은 사실을 두고 사람은
 * 모자란 쪽이 아니라 **다음에 무엇을 하면 되는지**를 말한다.
 *
 * 들어오는 것은 결과 모델이 만든 빈자리 문장이고, 여기서 판정을 다시 하지
 * 않는다. 바뀌는 것은 그 사실을 적는 꼴뿐이다.
 */
export function nextStepKo(need: string): string {
  const t = need.trim()
    .replace(/\s*아직\s*적지\s*않으셨(어요|습니다)\.?$/, "")
    .replace(/\s*아직\s*없(어요|습니다)\.?$/, "")
    .replace(/[.]$/, "")
    .trim();
  if (!t) return "";
  return `다음 과제에서는 ${t} 한 줄만 적어두면 좋아요.`;
}

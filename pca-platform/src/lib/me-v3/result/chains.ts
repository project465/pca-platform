/**
 * 그 Core 의 그 영역이 일하는 차례.
 *
 * **모르는 Core 와 모르는 영역에는 차례가 없다.** 빈 배열을 돌려주면
 * 부르는 쪽이 차례 없는 문장을 쓰고, 그것은 틀린 차례를 적는 것보다 낫다.
 */
export function chainFor(core: string, domain: string | null): string[] {
  if (!domain) return [];
  return CHAIN_KO[core]?.[domain] ?? [];
}

/**
 * **할 일이 몇 가지인가는 이 함수 하나가 정한다**(2026-11-03 전주대 실제 화면 J7).
 *
 * 책 07장 로드맵은 할 일을 여덟까지 달력에 올리는데, 웹은 크게 띄운 하나와 `이어지는 할 일` 셋까지만
 * 세어 `할 일 3개` 로 적었다. 같은 결과를 두고 화면은 3, 종이는 5 처럼 갈렸다. 책과 웹이 같은 목록을
 * 읽고 같은 수를 적는다. 할 일의 차례와 내용은 결과 모델이 정한 그대로다(여기서 고르지 않는다)
 */
export const PLAN_MAX = 8;
export function planActions<T>(actions: readonly T[]): T[] {
  return actions.slice(0, PLAN_MAX);
}

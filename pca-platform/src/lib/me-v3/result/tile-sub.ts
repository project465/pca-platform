const BY_CORE: Record<string, Record<string, string>> = {
  BIZ_CORE_V1: BIZ,
};

/** 카드 세부 한 줄. 적어 두지 않은 Core 는 `domainSub` 로 간다 */
export function tileSub(core: string, code: string): string {
  return BY_CORE[core]?.[code] ?? domainSub(core, code);
}

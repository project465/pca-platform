/** 태그 밖의 글만 바꾼다 */
export function forAgency(html: string): string {
  /* 참여자가 직접 쓴 글(“…”, data-own)은 원문 그대로 둔다(2026-11-03 견본: 직접 쓴 "다음 학기" 가 "다음 기간" 으로 실렸다) */
  return html.split(/(<[^>]+>|“[^”<]*”)/).map((part) => {
    if (part.startsWith("<") || part.startsWith("“")) return part;
    let t = part;
    for (const [re, to] of RULES) t = t.replace(re, to as never);
    return t;
  }).join("");
}

/**
 * 영문 · 숫자 낱말 뒤 조사의 띄어쓰기를 붙인다(`3D CAD 로` → `3D CAD로` · 2026-11-02 진흥원 시험 N13).
 * 사전 원고가 영문 낱말 뒤를 띄워 적은 줄이 있다. 조사가 분명한 것(로 · 으로 · 를 · 을 · 와 · 과)만 붙이고 태그 안은 건드리지 않는다
 */
export function tidyKo(html: string): string {
  return html.split(/(<[^>]+>)/).map((part) => (part.startsWith("<") ? part
    : part.replace(/([A-Za-z0-9)]) (으로|로|를|을|와|과)(?=[\s,.·)’”]|$)/g, "$1$2"))).join("");
}

/**
 * **검사는 한 번 본다**(2026-11-02 전주대 시험 JA6). `다시 검사 · 다음 검사` 를 권하지 않는다. 결과 뒤에 더한 경험은
 * 경험 기록에 적으면 내 CareerMatri 의 `현재 상태` 에 반영되므로 그쪽으로 이끈다. 재응시는 학교 담당자가 열 때만이다
 */
const ONE_TEST: [RegExp, string][] = [
  /* 문장 통째로 먼저 바꾼다. 낱말만 바꾸면 `남겨 두면 경험 기록에 더하면` 처럼 조건이 두 번 겹친다(2026-11-03 견본 P2) */
  [/다음 검사에서 고르면 그 산업으로 바뀝니다/g, "내 CareerMatri에서 목표 산업을 고르면 그 산업으로 바뀝니다"],
  [/다음 검사에서는? ‘해 본 적 있다’로 답할 수 있/g, "경험 기록에 ‘해 본 적 있다’로 남길 수 있"],
  [/다음 검사에서 한 걸음 더 채우면/g, "경험 기록을 더한 현재 상태에서 한 걸음 더 채우면"],
  [/다음 검사에서 ‘해 봤다’로 답해도 되는지/g, "경험 기록에 ‘해 봤다’로 더해도 되는지"],
  [/나눠 답하면 다음 검사에서 또렷해집니다/g, "나눠 적으면 경험 기록에서 또렷해집니다"],
  [/다음 검사에서 그 영역을 ‘해 봤다’로 답할 수 있는지/g, "그 영역을 경험 기록에 ‘해 봤다’로 더할 수 있는지"],
  [/다시 검사할 때 고쳐 적어 보세요/g, "내 CareerMatri에서 고쳐 적어 보세요"],
  [/다음 검사 리포트/g, "경험 기록을 더한 현재 상태"],
  [/다음 검사에서는/g, "경험 기록에 더하면"],
  [/다음 검사에서/g, "경험 기록에 더하면"],
  [/다시 검사할 때/g, "경험 기록을 더할 때"],
  [/다시 검사해 보세요/g, "경험 기록에 적어 보세요"],
  [/같은 검사를 다시 보고/g, "경험 기록을 더한 현재 상태를 보고"],
  [/같은 검사를 다시 보아/g, "경험 기록을 더해"],
  [/다시 검사/g, "현재 상태 다시 보기"],
];
export function oneTest(html: string): string {
  return html.split(/(<[^>]+>)/).map((part) => {
    if (part.startsWith("<")) return part;
    let t = part;
    for (const [re, to] of ONE_TEST) t = t.replace(re, to);
    return t;
  }).join("");
}

/**
 * **일자리 기관 참여자의 책**(2026-11-02 세종일자리경제진흥원 시험: 참여자는 학생이 아닌데 "설계 수업에서…",
 * "캡스톤", "수업에서 다뤄 본 값" 이 나왔다).
 *
 * 문장마다 기관 유형을 묻게 고치면 장마다 두 벌이 생긴다. 그래서 다 지은 쪽의 글에서 학교에만 맞는 말을
 * 현장 · 직업훈련 · 이전 직장에 맞는 말로 바꾼다. **뒤따르는 조사까지 같이 바꾼다**(받침이 달라지는 말).
 * HTML 태그 안(속성)은 건드리지 않는다.
 */
const RULES: [RegExp, string | ((...m: string[]) => string)][] = [
  [/설계 수업/g, "실무 교육"],
  [/캡스톤 ?디자인/g, "실무 프로젝트"],
  /* 받침 있는 말 → 받침 없는 말: 조사를 함께 고친다 */
  [/캡스톤(을|이|은|과)?/g, (_m, j) => `실무 프로젝트${j ? ({ 을: "를", 이: "가", 은: "는", 과: "와" } as Record<string, string>)[j] : ""}`],
  [/(?<![대재휴])학생(을|이|은|과)(?=[\s,.)·’”]|$)/g, (_m, j) => `참여자${({ 을: "를", 이: "가", 은: "는", 과: "와" } as Record<string, string>)[j]}`],
  /* `학생회` · `학생증` · `대학생` 같은 말은 그대로 둔다 */
  [/(?<![대재휴])학생(?![회증])/g, "참여자"],
  [/수업이나 과제/g, "교육이나 일"],
  [/수업이나 팀 과제/g, "교육이나 팀 업무"],
  [/수업과 팀 과제/g, "교육과 팀 업무"],
  [/수업에서/g, "교육이나 일에서"],
  [/수업/g, "교육"],
  [/이번 학기/g, "이번 기간"],
  [/다음 학기/g, "다음 기간"],
  [/학기/g, "기간"],
  [/학부 과정/g, "교육 과정"],
];

/** 태그 밖의 글만 바꾼다 */
export function forAgency(html: string): string {
  return html.split(/(<[^>]+>)/).map((part) => {
    if (part.startsWith("<")) return part;
    let t = part;
    for (const [re, to] of RULES) t = t.replace(re, to as never);
    return t;
  }).join("");
}

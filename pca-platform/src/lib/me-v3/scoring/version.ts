/**
 * 2차 문항 은행. 1차는 `me-v3-items.json` 에 동결해 둔다.
 *
 * `.1` 로 올린 까닭. 문면이 바뀐 것이 아니라 **문항이 바뀌었다**: 석사 이상
 * 한 묶음 여섯이 석사·박사·포닥 세 묶음 열여덟로 갈렸고, 영역 훑기의
 * `잘 모르겠다` 가 값 자리에 `null` 을 들게 됐고, 선별 축 둘째 문항의
 * 등급이 STANDARD 로 올라갔다.
 *
 * `.2` 로 올린 까닭. **영역 이름의 영문 약어를 한국어로 바꿨다**
 * (`동역학·진동·NVH` → `동역학·진동·소음`). NVH 는 자동차 쪽에서 쓰는
 * 말이고 학부생과 다른 산업 쪽에서는 읽히지 않는데, 그 이름이 격자 줄과
 * 머리말과 결과지에 그대로 나갔다. NVH 는 세부 영역에 남겼다: 그 자리에
 * 서는 영역 이름을 대신하지 않고 그 안의 한 갈래로 읽혀서 아는 사람이 찾는다.
 * **판정은 한 줄도 바뀌지 않는다**: 영역 코드가 그대로라 같은 응답이 같은
 * 묶음으로 간다. 문항 은행 판본만 올린다.
 *
 * `.3` 으로 올린 까닭 셋. 전부 **중복을 줄인 것**이고 문항 수는 그대로다.
 *
 * ① **역할팩과 산업팩이 Core 문항을 베끼고 있었다.** 어미만 `적이` 에서
 * `경험이` 로 바꾼 자리가 있었다(`구속 조건과 하중 작용점을 직접 정해 본`).
 * 그러면 응시자는 같은 질문을 두 번 받고, 역할팩이 파는 것(그 자리에서
 * 가진 권한과 범위)이 사라진다. 스물아홉 문항을 다시 썼다.
 *
 * ② **번역 열 단계에 수정(J7)이 없었다.** 검증(J6)을 두 번 묻고 있었다.
 * 경험 번역이 문제에서 활용까지 가는 길인데 그 가운데 한 칸이 비어 있었다.
 * 한 문항의 축과 문면을 고쳤고 `쓴 방법` 은 판단(J3)에서 방법(J4)으로 옮겼다.
 *
 * ③ **한 응시가 한 칸에 여섯 문항까지 받고 있었다.** 선별 둘과 심화 하나에
 * 산업 둘과 역할 둘이 같은 (영역 · 축)에 얹히는 자리가 있었다. 묻는 것이
 * 다른 판단이면 축도 다르므로 여덟 문항의 축을 뜻에 맞게 옮겼고, 같은
 * 판단을 두 번 묻던 한 문항은 다시 썼다. 이제 가장 많은 자리가 넷이다.
 *
 * **판정 규칙은 한 줄도 바뀌지 않았다.** 다만 축이 옮겨진 문항이 있으므로
 * 같은 응답이 다른 칸으로 간다. 그래서 채점 판본도 함께 올린다.
 */

/**
 * 판단 규칙이 바뀌면 올린다. 문면이 바뀌는 것은 문항 은행 판본이다.
 *
 * `.2` 로 올린 까닭. 선별 네 축의 넷째가 조직 활용에서 실패·수정으로
 * 바뀌었다. 축 상태를 내는 규칙과 묶음 판정과 근거 세는 법은 한 줄도
 * 바뀌지 않았지만, **선별 등급에서 세는 축이 달라지면 같은 응답이 다른
 * 묶음으로 간다.** 그것은 판단 규칙이 바뀐 것이므로 판본을 올린다.
 *
 * `.3` 으로 올린 까닭 셋.
 *
 * ① `잘 모르겠다` 가 **수에서 상태로** 바뀌었다. 영역 훑기의 관심과 배울
 * 뜻에서 그 보기가 가운데 값(3)으로 저장되고 있었고, 그래서 아직 모르는
 * 사람이 `보통 관심` 으로 판정됐다. 이제 `ANSWERED_UNKNOWN` 으로 보존하고
 * 구간을 내지 않는다. **같은 응답이 다른 구간으로 간다**: 판단 규칙이다.
 *
 * ② 학위 묶음이 하나에서 **넷**으로 갈렸다. 어느 묶음이 열리는지가 학위로
 * 정해지고, 받지 않은 묶음의 응답은 세지 않는다.
 *
 * ③ 선별 축의 **둘째 문항이 STANDARD 부터**다. 선별 등급에는 소유 판정이
 * 없어서 둘째 자리가 뜻을 가지지 않는다. 그 등급에서 묻지 않으므로 그
 * 문항은 `NOT_ROUTED` 다.
 *
 * `.4` 로 올린 까닭 둘.
 *
 * ① **과대 보고 어긋남이 한 번도 돌지 않았다.** `quality.ts` 가 묶음 이름을
 * `DEEP-J8` 과 `PROBE-J4` 로 적어 두었는데 어느 판본에도 없는 이름이다.
 * for 문의 몸통이 영원히 건너뛰어져서 `CHECKLIST_MISMATCH_HIGH` 가 0 이었다.
 * 지금 묶음 이름으로 고쳤으므로 **같은 응답이 다른 품질 표시를 받을 수
 * 있다**: 판단 규칙이다.
 *
 * ② 스냅샷이 들고 다니는 칸이 넷 늘었다(`context.common` · `.xfield` ·
 * `.forced` · 팩의 `answers`). **축 수준과 묶음 판정은 한 줄도 바뀌지
 * 않았다.** 그런데도 올리는 까닭은 스냅샷의 모양이 달라져서, 옛 판본으로
 * 적힌 줄과 새 줄을 같은 것으로 읽으면 안 되기 때문이다.
 *
 * `.5` 로 올린 까닭. **판정 규칙은 그대로이고 문항의 축이 옮겨졌다.**
 * 팩 문항 여덟과 번역 한 문항의 `evidence_axis` 가 바뀌어서, 같은 응답이
 * 다른 칸으로 간다. 규칙이 같아도 들어가는 자리가 달라지면 결과가 달라지고,
 * 그것은 판본을 올릴 일이다.
 */

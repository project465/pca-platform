-- ============================================================
--  ME_V3 응시의 언어 (영어판 1차, 2026-10-24)
--
--  **언어는 응시가 들고 다닌다.** 시작할 때 한 번 정하고 바꾸지 않는다.
--  한 응시 안에서 화면 · 결과 · PDF 가 같은 언어여야 하기 때문이다:
--  쿠키로 그때그때 고르면 영어로 답한 사람의 결과지가 한국어로 열리는
--  날이 온다.
--
--  **채점은 이 칸을 읽지 않는다.** 문항 id · 축 · 보기 차례가 두 언어에서
--  같고, 같은 응답이면 같은 판정이 나온다(`npm run v3:i18n` 의 골든).
--
--  이미 있는 줄은 전부 한국어로 받았으므로 기본값이 곧 맞는 값이다.
--  CHECK 를 칸과 함께 세우는 까닭은 `ADD COLUMN IF NOT EXISTS` 가 두 번째
--  돌 때 제약을 다시 만들지 않게 하려는 것이다(이 파일은 배포마다 돈다).
-- ============================================================

ALTER TABLE v3_attempts ADD COLUMN IF NOT EXISTS locale TEXT NOT NULL DEFAULT 'ko'
  CONSTRAINT v3_attempts_locale_check CHECK (locale IN ('ko', 'en'));

COMMENT ON COLUMN v3_attempts.locale IS
  '응시 언어. 시작할 때 정하고 바꾸지 않는다. 채점에 들어가지 않는다';
